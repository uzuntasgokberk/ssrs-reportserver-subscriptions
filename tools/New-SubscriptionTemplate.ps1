#requires -Version 5.1

<#
.SYNOPSIS
    Builds the Subscriptions.xlsx template (example rows + "How to use" sheet) from scratch.

.DESCRIPTION
    The template in the repository is generated by this script instead of being saved in Excel, so
    that no author name, company or sensitivity label ends up in the file. Change this script and run
    it again to change the template.

    Needs the ImportExcel module (Install-Module ImportExcel -Scope CurrentUser).

.PARAMETER Path
    Output file. Default: Subscriptions.xlsx in the repository root. An existing file is replaced.

.EXAMPLE
    .\tools\New-SubscriptionTemplate.ps1
#>
[CmdletBinding(PositionalBinding = $false)]
param(
    [string]$Path
)

$ErrorActionPreference = 'Stop'
if (-not $Path) { $Path = Join-Path (Split-Path -Parent $PSScriptRoot) 'Subscriptions.xlsx' }
Import-Module ImportExcel
if (Test-Path -LiteralPath $Path) { Remove-Item -LiteralPath $Path }

function ConvertTo-ExcelTime {
    # Excel stores a time of day as a fraction of a day: 08:00 -> 0.3333
    param([int]$Hour, [int]$Minute)
    return [double](($Hour * 60 + $Minute) / 1440.0)
}

function New-ExampleRow {
    param([string]$Name, [string]$ReportPath, [string]$ScheduleType, [string]$ScheduleDetail, [double]$RunTime,
          $StartDate, [string]$To, [string]$Cc, [string]$Bcc, [string]$Subject, [string]$RenderFormat,
          [string]$Comment, [bool]$IncludeLink, [string]$Parameters)
    # The column order is the order of the template; the script itself matches columns by name.
    return [pscustomobject][ordered]@{
        Enabled = $false; SubscriptionName = $Name; ReportPath = $ReportPath; ScheduleType = $ScheduleType
        RunTime = $RunTime; StartDate = $StartDate; To = $To; Cc = $Cc; Bcc = $Bcc; Subject = $Subject
        RenderFormat = $RenderFormat; Comment = $Comment; IncludeLink = $IncludeLink; ExpectedOwner = ''
        Parameters = $Parameters; ScheduleDetail = $ScheduleDetail
    }
}

$rows = @(
    (New-ExampleRow -Name 'Daily Sales - Management' -ReportPath '/Sales/Daily Sales' -ScheduleType 'Daily' -ScheduleDetail '' `
        -RunTime (ConvertTo-ExcelTime 8 0) -StartDate $null -To 'sales.manager@example.com' -Cc 'sales.team@example.com' -Bcc '' `
        -Subject 'Daily Sales Report' -RenderFormat 'EXCELOPENXML' -Comment 'The daily sales report is attached.' -IncludeLink $false -Parameters 'Region=North,South')
    (New-ExampleRow -Name 'Stock Levels - Mon and Thu' -ReportPath '/Inventory/Stock Levels' -ScheduleType 'Weekly' -ScheduleDetail 'Mon,Thu' `
        -RunTime (ConvertTo-ExcelTime 7 30) -StartDate $null -To 'warehouse@example.com' -Cc '' -Bcc '' `
        -Subject 'Stock Levels' -RenderFormat 'PDF' -Comment '' -IncludeLink $true -Parameters '')
    (New-ExampleRow -Name 'Revenue - 1st and 15th' -ReportPath '/Finance/Monthly Revenue' -ScheduleType 'Monthly' -ScheduleDetail '1;15' `
        -RunTime (ConvertTo-ExcelTime 9 0) -StartDate $null -To 'finance@example.com' -Cc '' -Bcc 'controlling@example.com' `
        -Subject 'Monthly Revenue' -RenderFormat 'EXCELOPENXML' -Comment '' -IncludeLink $false -Parameters '')
    (New-ExampleRow -Name 'Open Orders - Every 2 Hours' -ReportPath '/Operations/Open Orders' -ScheduleType 'Hourly' -ScheduleDetail '2' `
        -RunTime (ConvertTo-ExcelTime 8 0) -StartDate $null -To 'operations@example.com' -Cc '' -Bcc '' `
        -Subject 'Open Orders' -RenderFormat 'CSV' -Comment '' -IncludeLink $false -Parameters '')
    (New-ExampleRow -Name 'Board Pack - Year End' -ReportPath '/Finance/Board Pack' -ScheduleType 'Once' -ScheduleDetail '' `
        -RunTime (ConvertTo-ExcelTime 9 0) -StartDate ([datetime]'2027-01-04') -To 'board@example.com' -Cc '' -Bcc '' `
        -Subject 'Board Pack 2026' -RenderFormat 'PDF' -Comment '' -IncludeLink $false -Parameters 'Year=2026')
)

# ---- Subscriptions ----
$xl = $rows | Export-Excel -Path $Path -WorksheetName 'Subscriptions' -TableName 'SubscriptionsTable' -TableStyle Medium2 -FreezeTopRow -NoNumberConversion * -PassThru
$ws = $xl.Workbook.Worksheets['Subscriptions']
$widths = @(10, 32, 30, 14, 10, 12, 30, 26, 26, 24, 15, 36, 12, 22, 26, 16)   # columns A..P
for ($c = 0; $c -lt $widths.Count; $c++) { $ws.Column($c + 1).Width = $widths[$c] }
$ws.Column(5).Style.Numberformat.Format  = 'hh:mm'        # RunTime
$ws.Column(6).Style.Numberformat.Format  = 'yyyy-mm-dd'   # StartDate
$ws.Column(15).Style.Numberformat.Format = '@'            # Parameters: text
$ws.Column(16).Style.Numberformat.Format = '@'            # ScheduleDetail: text, so "1,15" does not become a decimal number
foreach ($c in 5, 6) { $ws.Cells[2, $c, ($rows.Count + 1), $c].Style.Numberformat.Format = $ws.Column($c).Style.Numberformat.Format }

$lists = @(
    @{ Range = 'D2:D1000'; Title = 'ScheduleType'; Text = 'Use Daily, Weekly, Monthly, Hourly or Once.'; Values = @('Daily', 'Weekly', 'Monthly', 'Hourly', 'Once') }
    @{ Range = 'K2:K1000'; Title = 'RenderFormat'; Text = 'Pick a format from the list.'; Values = @('EXCELOPENXML', 'PDF', 'CSV', 'WORDOPENXML', 'MHTML', 'IMAGE', 'XML', 'PPTX', 'ATOM') }
    @{ Range = 'A2:A1000'; Title = 'TRUE or FALSE'; Text = 'Enter TRUE or FALSE.'; Values = @('TRUE', 'FALSE') }
    @{ Range = 'M2:M1000'; Title = 'TRUE or FALSE'; Text = 'Enter TRUE or FALSE.'; Values = @('TRUE', 'FALSE') }
)
foreach ($l in $lists) {
    $dv = $ws.DataValidations.AddListValidation($l.Range)
    foreach ($v in $l.Values) { $dv.Formula.Values.Add($v) }
    $dv.ShowErrorMessage = $true
    $dv.ErrorTitle = $l.Title
    $dv.Error = $l.Text
}

# ---- How to use ----
$help = $xl.Workbook.Worksheets.Add('How to use')
$help.Cells['A1'].Value = 'SSRS e-mail subscriptions from Excel'
$help.Cells['A1'].Style.Font.Bold = $true
$help.Cells['A1'].Style.Font.Size = 14
$steps = @(
    '1. Fill in one row per subscription on the Subscriptions sheet. Set Enabled to TRUE when the row is ready.',
    '2. Preview (changes nothing):  .\Import-SsrsSubscriptions.ps1 -ReportServerUrl "http://reportserver/ReportServer"',
    '3. Read the log in the Logs folder. Fix the rows marked ERROR and run the preview again.',
    '4. Apply: run the same command with -Apply. If any row has an error, nothing is changed.',
    '5. To update existing subscriptions from this file: add -Overwrite (preview), then -Overwrite -Apply.',
    'Deleting a row or renaming SubscriptionName does not delete the subscription on the server. Delete it in the web portal.'
)
for ($i = 0; $i -lt $steps.Count; $i++) { $help.Cells[($i + 3), 1].Value = $steps[$i] }

$columns = @(
    @('Enabled', 'Yes', 'TRUE = process the row. FALSE or empty = skip it.', 'TRUE'),
    @('SubscriptionName', 'Yes', 'Name of the subscription (Description in SSRS). Must be unique per report: re-runs match on ReportPath + SubscriptionName.', 'Daily Sales - Management'),
    @('ReportPath', 'Yes', 'Path of the report on the report server, not a URL.', '/Sales/Daily Sales'),
    @('ScheduleType', 'Yes', 'Daily, Weekly, Monthly, Hourly or Once.', 'Weekly'),
    @('RunTime', 'Yes', 'Time of day, in the time zone of the report server. For Hourly: the first run of the day.', '08:00'),
    @('StartDate', 'No', 'First day of the schedule. Empty = today (or tomorrow if RunTime has passed). Required in practice for Once.', '2027-01-04'),
    @('To', 'Yes', 'Recipients, separated with ; or ,', 'a@example.com;b@example.com'),
    @('Cc', 'No', 'Copy recipients.', 'team@example.com'),
    @('Bcc', 'No', 'Blind copy recipients.', 'archive@example.com'),
    @('Subject', 'Yes (column)', 'Mail subject. Empty cell = SSRS default: @ReportName was executed at @ExecutionTime', 'Daily Sales Report'),
    @('RenderFormat', 'Yes', 'EXCELOPENXML, PDF, CSV, WORDOPENXML, MHTML, IMAGE, XML, PPTX or ATOM.', 'EXCELOPENXML'),
    @('Comment', 'No', 'Text in the mail body.', 'The report is attached.'),
    @('IncludeLink', 'No', 'TRUE = also include a link to the report. Empty = FALSE.', 'FALSE'),
    @('ExpectedOwner', 'No', 'DOMAIN\user that must run the script. The owner of a subscription is always the account that runs the script.', 'CONTOSO\svc-reports'),
    @('Parameters', 'No', 'Report parameters: name=value; name2=value1,value2. Empty = the report defaults. Use the value, not the label.', 'Region=North,South; Year=2026'),
    @('ScheduleDetail', 'Depends', 'Weekly: days (Mon,Thu / Weekdays / Weekend). Monthly: days of the month (1;15 or 1-5). Hourly: every N hours (1-24, empty = 1). Daily and Once: leave empty.', 'Mon,Thu')
)
$headerRow = $steps.Count + 5
$help.Cells[($headerRow - 1), 1].Value = 'Columns of the Subscriptions sheet'
$help.Cells[($headerRow - 1), 1].Style.Font.Bold = $true
$header = @('Column', 'Required', 'What to enter', 'Example')
for ($c = 0; $c -lt $header.Count; $c++) {
    $help.Cells[$headerRow, ($c + 1)].Value = $header[$c]
    $help.Cells[$headerRow, ($c + 1)].Style.Font.Bold = $true
}
for ($r = 0; $r -lt $columns.Count; $r++) {
    for ($c = 0; $c -lt 4; $c++) { $help.Cells[($headerRow + 1 + $r), ($c + 1)].Value = $columns[$r][$c] }
}
$help.Column(1).Width = 18
$help.Column(2).Width = 13
$help.Column(3).Width = 95
$help.Column(4).Width = 32
$help.Cells[($headerRow + 1), 3, ($headerRow + $columns.Count), 3].Style.WrapText = $true
$help.Cells[($headerRow + 1), 1, ($headerRow + $columns.Count), 4].Style.VerticalAlignment = 'Top'

# ---- Document properties: nothing personal ----
$xl.Workbook.Properties.Author = ''
$xl.Workbook.Properties.LastModifiedBy = ''
$xl.Workbook.Properties.Company = ''
$xl.Workbook.Properties.Title = 'SSRS e-mail subscriptions'
$ws.Select()
$xl.Workbook.View.ActiveTab = 0
Close-ExcelPackage $xl
Write-Verbose ('Template written: {0}' -f $Path)
